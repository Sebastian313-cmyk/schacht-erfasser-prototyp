  Future<void> _save() async {
    if (_evnrCtrl.text.trim().isEmpty ||
        _strasseCtrl.text.trim().isEmpty ||
        _erfCtrl.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Bitte alle Pflichtfelder ausfüllen.')),
      );
      return;
    }
    final s = SessionData(
      evnr: _evnrCtrl.text.trim(),
      strasse: _strasseCtrl.text.trim(),
      erfasser: _erfCtrl.text.trim(),
      wetter: _wetter,
      zeitIso: _zeit.toIso8601String(),
      temperatur: _temperaturCtrl.text.trim(),
      nisPlanPdf: _nisPlanPdfBase64,
    );
    await SessionStore.save(s);
    await _loadKnownEvNrs();
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Erfasserdaten gespeichert.')),
      );
      setState(() => _currentStep = 1);
    }
  }

  Future<void> _importData() async {
    try {
      final result = await FilePicker.platform.pickFiles(
        type: FileType.custom,
        allowedExtensions: ['zip', 'json'],
        withData: true,
      );
      if (result == null || result.files.isEmpty) return;

      final ausgewaehlt = result.files.first;
      final dateiname = ausgewaehlt.name;
      Uint8List? bytes = ausgewaehlt.bytes;

      if (bytes == null) {
        if (kIsWeb) {
          if (!mounted) return;
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text(
                'Import fehlgeschlagen: Datei konnte nicht gelesen werden. Bitte erneut auswählen.',
              ),
            ),
          );
          return;
        }
        if (ausgewaehlt.path == null) {
          if (!mounted) return;
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text('Import fehlgeschlagen: kein Dateipfad gefunden.'),
            ),
          );
          return;
        }
        final xfile = XFile(ausgewaehlt.path!);
        bytes = await xfile.readAsBytes();
      }

      if (!mounted) return;
      showDialog(
        context: context,
        barrierDismissible: false,
        builder: (ctx) => const AlertDialog(
          title: Text('Import läuft...'),
          content: SizedBox(
            height: 80,
            child: Center(child: CircularProgressIndicator()),
          ),
        ),
      );

      await import_export_service.loadLibrary();
      final ext = (ausgewaehlt.extension ?? '').toLowerCase();
      (int, int) importErgebnis;
      if (ext == 'json') {
        importErgebnis = await import_export_service
            .ImportExportService.importiereJson(bytes);
      } else {
        importErgebnis = await import_export_service
            .ImportExportService.importiereDaten(bytes);
      }
      final (evAnzahl, eintragAnzahl) = importErgebnis;

      if (mounted) Navigator.of(context).pop();

      await _loadKnownEvNrs();

      if (!mounted) return;
      final msg = (evAnzahl == 0 && eintragAnzahl == 0)
          ? 'Keine Einträge gefunden in $dateiname. Bitte prüfen, ob die ZIP/JSON eine erfassungen.json oder gültige Struktur enthält.'
          : '✓ Importiert: $evAnzahl EVNr, $eintragAnzahl Einträge aus $dateiname';

      ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(msg)));
      setState(() => _currentStep = 1);
    } catch (e) {
      if (mounted) Navigator.of(context).pop();
      if (!mounted) return;
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text('Fehler beim Import: $e')));
    }
  }

