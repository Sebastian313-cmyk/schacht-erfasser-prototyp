  // EVNr-Auswahl und Session-Übernahme
  Future<void> _continueWithEv(String evnr) async {
    try {
      final metas = await SpeicherService.ladeEintraegeFuerEvNr(evnr);
      if (metas.isNotEmpty) {
        final m = metas.first;
        _evnrCtrl.text = evnr;
        final str = (m['strasse'] as String?)?.trim();
        if (str != null && str.isNotEmpty) _strasseCtrl.text = str;
        final erf = (m['erfasser'] as String?)?.trim();
        if (erf != null && erf.isNotEmpty) _erfCtrl.text = erf;
        final wet = (m['wetter'] as String?)?.trim();
        if (wet != null && wet.isNotEmpty) _wetter = wet;
        final temp = (m['temperatur'] as String?)?.trim();
        if (temp != null && temp.isNotEmpty) _temperaturCtrl.text = temp;
        final zi = (m['zeitIso'] as String?)?.trim();
        final dt = zi == null ? null : DateTime.tryParse(zi);
        if (dt != null) _zeit = dt;
        // NIS-Plan PDF laden (pro EVNr)
        final nisFromStore = await SessionStore.loadNisPlanForEvnr(evnr);
        if (nisFromStore != null && nisFromStore.pdfBase64.trim().isNotEmpty) {
          _nisPlanPdfBase64 = nisFromStore.pdfBase64;
          _nisPlanFileName = nisFromStore.fileName ?? 'NIS-Plan.pdf';
        } else {
          final nisPdf = (m['nisPlanPdf'] as String?)?.trim();
          if (nisPdf != null && nisPdf.isNotEmpty) {
            _nisPlanPdfBase64 = nisPdf;
            _nisPlanFileName = 'NIS-Plan.pdf';
            await SessionStore.saveNisPlanForEvnr(
              evnr,
              nisPdf,
              fileName: 'NIS-Plan.pdf',
            );
          } else {
            _nisPlanPdfBase64 = null;
            _nisPlanFileName = null;
          }
        }
        if (mounted) setState(() {});
        await _save();
      } else {
        _evnrCtrl.text = evnr;
      }
    } catch (_) {
      _evnrCtrl.text = evnr;
    }
  }
