        if (!mounted) return;
        final overwrite = await showDialog<bool>(
          context: context,
          builder: (ctx) => AlertDialog(
            title: const Text('Test-Daten vorhanden'),
            content: const Text(
              'Test-Daten (99000) existieren bereits. Überschreiben?',
            ),
            actions: [
              TextButton(
                onPressed: () => Navigator.of(ctx).pop(false),
                child: const Text('Abbrechen'),
              ),
              FilledButton(
                onPressed: () => Navigator.of(ctx).pop(true),
                child: const Text('Überschreiben'),
              ),
            ],
          ),
        );
        if (overwrite != true) return;
        await test_data_seeder.TestdatenSeeder.clearTestData();
      }
      await test_data_seeder.TestdatenSeeder.seedTestdaten();
      if (!mounted) return;
      final testSession = SessionData(
        evnr: '99000',
        strasse: 'Musterstrasse 1',
        erfasser: 'Test-Erfasser',
        wetter: 'bewoelkt',
        zeitIso: DateTime.now().toIso8601String(),
        temperatur: '18',
        nisPlanPdf: _nisPlanPdfBase64,
      );
      await SessionStore.save(testSession);
      _evnrCtrl.text = testSession.evnr;
      _strasseCtrl.text = testSession.strasse;
      _erfCtrl.text = testSession.erfasser;
      _temperaturCtrl.text = testSession.temperatur;
      _wetter = testSession.wetter;
      _evnrIsAutoGenerated = false;
      await _loadKnownEvNrs();
      if (!mounted) return;
      setState(() => _currentStep = 1);
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('✓ Test-Daten erstellt! EVNr: 99000 (Musterstraße 1)'),
