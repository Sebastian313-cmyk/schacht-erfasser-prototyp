/// Startbildschirm der App
class StartBildschirm extends StatefulWidget {
  const StartBildschirm({super.key});
  @override
  State<StartBildschirm> createState() => _StartBildschirmState();
}

class _StartBildschirmState extends State<StartBildschirm>
    with WidgetsBindingObserver {
  // State-Variablen
  final _evnrCtrl = TextEditingController();
  final _strasseCtrl = TextEditingController();
  final _erfCtrl = TextEditingController();
  final _temperaturCtrl = TextEditingController();
  String _wetter = 'klar';
  DateTime _zeit = DateTime.now();
  int _currentStep = 0;
  List<String> _knownEvNrs = const [];
  Map<String, bool> _evnrHasNis = {}; // Track welche EVNr NIS-Plan haben
  bool _loadingEvNrs = false;
  String? _nisPlanPdfBase64;
  String? _nisPlanFileName;
  String _lastNisEvnr = '';
  String _lastAutoEvnrValue = '';
  bool _evnrIsAutoGenerated = false;
  bool _resolvingAutoData = false;
  Timer? _evnrLoadDebounce;

  String _yearPrefix(DateTime dt) => (dt.year % 100).toString().padLeft(2, '0');

  String _buildAutoEvnrForYear(DateTime dt) {
    return _yearPrefix(dt);
  }

  void _applyAutoEvnrForCurrentYear({bool forceForAutoValue = false}) {
    final current = _evnrCtrl.text.trim();
    if (current.isEmpty || (forceForAutoValue && _evnrIsAutoGenerated)) {
      final autoEvnr = _buildAutoEvnrForYear(_zeit);
      _lastAutoEvnrValue = autoEvnr;
      _evnrIsAutoGenerated = true;
      _evnrCtrl.text = autoEvnr;
    }
  }

  // Methoden
  Future<void> _loadKnownEvNrs() async {
    if (_loadingEvNrs) return;
    if (mounted) setState(() => _loadingEvNrs = true);
    try {
      final evs = await SpeicherService.ladeAlleEvNr();
      final nisEvs = await SessionStore.loadNisPlanEvnrs();
      final combined = <String>[...evs];
      for (final ev in nisEvs) {
        if (!combined.contains(ev)) {
          combined.add(ev);
        }
      }
      if (!mounted) return;
      final nisSet = nisEvs.toSet();
      setState(() {
        _knownEvNrs = combined;
        _evnrHasNis = {for (final ev in combined) ev: nisSet.contains(ev)};
      });
    } catch (e) {
      debugPrint('Fehler beim Laden der EVNrs: $e');
      if (!mounted) return;
      setState(() {
        _knownEvNrs = const [];
        _evnrHasNis = {};
      });
    } finally {
      if (mounted) setState(() => _loadingEvNrs = false);
      _applyAutoEvnrForCurrentYear();
    }
  }

  void _setNow() => setState(() => _zeit = DateTime.now());

  Future<void> _navigateAndRefresh(String route) async {
    await Navigator.pushNamed(context, route);
    await _loadKnownEvNrs();
  }

  @override
  void initState() {
    super.initState();
    _applyAutoEvnrForCurrentYear();
    _evnrCtrl.addListener(_onEvnrChanged);
    WidgetsBinding.instance.addPostFrameCallback((_) {
      Future<void>.delayed(const Duration(milliseconds: 250), () {
        if (mounted) _loadKnownEvNrs();
      });
    });
  }

  @override
  void dispose() {
    _evnrLoadDebounce?.cancel();
    _evnrCtrl.removeListener(_onEvnrChanged);
    _evnrCtrl.dispose();
    _strasseCtrl.dispose();
    _erfCtrl.dispose();
    _temperaturCtrl.dispose();
    super.dispose();
  }

  void _onEvnrChanged() {
    final current = _evnrCtrl.text.trim();
    if (current != _lastAutoEvnrValue) {
      _evnrIsAutoGenerated = false;
    }
    _evnrLoadDebounce?.cancel();
    _evnrLoadDebounce = Timer(const Duration(milliseconds: 250), () {
      if (mounted) _loadNisForEvnr(_evnrCtrl.text.trim());
    });
  }

  Future<void> _loadNisForEvnr(String evnr) async {
    final e = evnr.trim();
    if (e == _lastNisEvnr) return;
    _lastNisEvnr = e;
    if (e.isEmpty) {
      if (!mounted) return;
      setState(() {
        _nisPlanPdfBase64 = null;
        _nisPlanFileName = null;
      });
      return;
    }
    final nis = await SessionStore.loadNisPlanForEvnr(e);
    if (!mounted) return;
    setState(() {
      _nisPlanPdfBase64 = nis?.pdfBase64;
      _nisPlanFileName = nis?.fileName;
    });
  }

  Future<void> _uploadNisPlan() async {
    final evnr = _evnrCtrl.text.trim();
    if (evnr.isEmpty) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Bitte zuerst eine EVNr eingeben.')),
      );
      return;
    }
    try {
      final result = await FilePicker.platform.pickFiles(
        type: FileType.custom,
        allowedExtensions: ['pdf'],
        withData: true,
      );
      if (result == null || result.files.isEmpty) return;

      final file = result.files.first;
      final bytes = file.bytes;
      if (bytes == null) {
        if (!mounted) return;
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Fehler: Datei konnte nicht gelesen werden'),
          ),
        );
        return;
      }

      final base64Pdf = base64Encode(bytes);
      setState(() {
        _nisPlanPdfBase64 = base64Pdf;
        _nisPlanFileName = file.name;
      });

      await SessionStore.saveNisPlanForEvnr(
        evnr,
        base64Pdf,
        fileName: file.name,
      );
      if (!mounted) return;
      setState(() {
        if (!_knownEvNrs.contains(evnr)) {
          _knownEvNrs = [evnr, ..._knownEvNrs];
        }
        _evnrHasNis = {..._evnrHasNis, evnr: true};
      });

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('✓ NIS-Plan hochgeladen: ${file.name}')),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text('Fehler beim Upload: $e')));
    }
  }

  Future<void> _openNisPlan() async {
    final evnr = _evnrCtrl.text.trim();
    final nis = evnr.isNotEmpty
        ? await SessionStore.loadNisPlanForEvnr(evnr)
        : null;
    final base64 = nis?.pdfBase64 ?? _nisPlanPdfBase64;
    if (base64 == null || base64.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Kein NIS-Plan hinterlegt.')),
      );
      return;
    }
    await nis_plan_viewer.loadLibrary();
    if (!mounted) return;
    showDialog(
      context: context,
      builder: (context) => nis_plan_viewer.NisPlanViewerDialog(
        pdfBase64: base64,
        fileName: nis?.fileName ?? _nisPlanFileName ?? 'NIS-Plan.pdf',
        evnr: evnr.isEmpty ? null : evnr,
        initialDrawings: nis?.drawings,
        initialRoutes: nis?.routes,
        initialStamps: nis?.stamps,
      ),
    );
  }

  Future<void> _setAllFromLocation() async {
    if (_resolvingAutoData) return;
    setState(() => _resolvingAutoData = true);

    String? street;
    String? wetter;
    String? temperatur;

    try {
      await Future.wait([
        gps_service.loadLibrary(),
        weather_service.loadLibrary(),
      ]);
      street = await gps_service.GpsService.getCurrentStreet();
      final weatherData = await weather_service
          .WeatherService.getCurrentWeatherAndTemperature();
      wetter = weatherData?['wetter']?.trim();
      temperatur = weatherData?['temperatur']?.trim();

      if (!mounted) return;

      var hasStreet = false;
      var hasWeather = false;

      if (street != null && street.trim().isNotEmpty) {
        _strasseCtrl.text = street.trim();
        hasStreet = true;
      }

      if (wetter != null &&
          wetter.isNotEmpty &&
          temperatur != null &&
          temperatur.isNotEmpty) {
        setState(() {
          _wetter = wetter!;
          _temperaturCtrl.text = temperatur!;
        });
        hasWeather = true;
      }

      String message;
      if (hasStreet && hasWeather) {
        message = 'Straße, Wetter und Temperatur automatisch gesetzt.';
      } else if (hasStreet) {
        message = 'Straße gesetzt. Wetter/Temperatur bitte manuell prüfen.';
      } else if (hasWeather) {
        message =
            'Wetter und Temperatur gesetzt. Straße bitte manuell eingeben.';
      } else {
        message =
            'Automatische Ermittlung nicht möglich. Bitte manuell eintragen.';
      }

      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text(message)));
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Automatische Erfassung fehlgeschlagen: $e')),
      );
    } finally {
      if (mounted) {
        setState(() => _resolvingAutoData = false);
      }
    }
  }

